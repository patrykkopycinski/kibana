/**
 * n>=30-per-pair extension of the pairwise routing-boundary dataset (t_d9046fa9).
 *
 * Same contract as collision_dataset.ts (which it supersedes for the powered run):
 *  - `sibling-owns`    - the sibling owns the request; loading endpoint-forensic-analysis is the misroute.
 *  - `az-owns`         - endpoint-forensic-analysis owns it; a sibling winning it is the reverse collision.
 *  - `az-must-not-load` - endpoint-forensic-analysis must not load at all (disclaimed capabilities).
 *
 * Power: 16 sibling-owns + 16 az-owns per pair (n=32/pair/arm), so a zero-misroute run bounds
 * the per-pair rate at <= ~9% (rule of three over 32) and a Wilson CI at n=32 is narrow enough
 * to test the "no collision" claim against a ~5% threshold. Prompts are individually authored
 * (not templated) so no single lexical field separates the classes: sibling-owns prompts may name
 * hosts, az-owns prompts may say "fleet"/"environment" — the discriminating signal is the REQUEST
 * (population-level pattern vs incident-scoped reconstruction), never a keyword.
 */

export type CollisionDirection = 'sibling-owns' | 'az-owns' | 'az-must-not-load';
export type SkillId =
  | 'endpoint-forensic-analysis'
  | 'threat-hunting'
  | 'alert-analysis'
  | 'elastic-defend-configuration-troubleshooting';

