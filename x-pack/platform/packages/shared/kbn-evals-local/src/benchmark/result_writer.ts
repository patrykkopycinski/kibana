import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { BenchmarkResult } from '../cli/benchmark';
import type { ModelConfig } from '../local/model_registry';

interface ModelsJson {
  platform: string;
  preferredRuntime: string;
  models: ModelConfig[];
}

export function writeResult(result: BenchmarkResult, pkgDir: string): void {
  const resultsDir = resolve(pkgDir, 'benchmark-results');
  if (!existsSync(resultsDir)) {
    mkdirSync(resultsDir, { recursive: true });
  }

  const filename = `${result.modelId}-${result.date}.json`;
  const filepath = resolve(resultsDir, filename);

  writeFileSync(filepath, JSON.stringify(result, null, 2) + '\n', 'utf8');
}

function deriveJudgeQuality(result: BenchmarkResult): string {
  if (!result.toolCallingPass) return 'poor';
  if (result.evalExitCode === 0) return 'very-good';
  return 'good';
}

export function updateRegistry(results: BenchmarkResult[], pkgDir: string): void {
  const modelsJsonPath = resolve(pkgDir, 'src', 'local', 'models.json');
  const raw = readFileSync(modelsJsonPath, 'utf8');
  const registry: ModelsJson = JSON.parse(raw);

  for (const result of results) {
    const existingIdx = registry.models.findIndex((m) => m.id === result.modelId);

    if (existingIdx >= 0) {
      const existing = registry.models[existingIdx];
      existing.tokPerSecEstimate = result.tokPerSec || existing.tokPerSecEstimate;
      existing.toolCalling = result.toolCallingPass;
      const quality = deriveJudgeQuality(result);
      if (quality !== 'poor') {
        existing.judgeQuality = quality as ModelConfig['judgeQuality'];
      }
    }
  }

  writeFileSync(modelsJsonPath, JSON.stringify(registry, null, 2) + '\n', 'utf8');
}

export function generateRecommendations(pkgDir: string): void {
  const modelsJsonPath = resolve(pkgDir, 'src', 'local', 'models.json');
  const raw = readFileSync(modelsJsonPath, 'utf8');
  const registry: ModelsJson = JSON.parse(raw);

  const models = registry.models.sort((a, b) => a.priority - b.priority);

  const ramTiers: Array<{ ram: string; model: ModelConfig | undefined }> = [
    { ram: '48 GB+', model: models.find((m) => m.minRamGb <= 48) },
    { ram: '32 GB', model: models.find((m) => m.minRamGb <= 32 && m.minRamGb > 16) },
    { ram: '16 GB', model: models.find((m) => m.minRamGb <= 16) },
  ];

  const lines: string[] = [
    '# Local Eval Model Recommendations',
    '',
    '> Auto-generated by `node scripts/evals local benchmark --update-registry`.',
    '> Do not edit manually -- run the benchmark to update.',
    '',
    '## Quick Pick by Machine',
    '',
    '| Machine RAM | Recommended Model | Judge Quality | Speed |',
    '|---|---|---|---|',
  ];

  for (const tier of ramTiers) {
    if (tier.model) {
      lines.push(
        `| ${tier.ram} | ${tier.model.name} (${tier.model.quantization}) | ${tier.model.judgeQuality} | ~${tier.model.tokPerSecEstimate} tok/s |`
      );
    }
  }

  lines.push('', '## All Tested Models', '');
  lines.push('| Model | Params | VRAM | Tool Calling | Judge Quality | tok/s | Priority |');
  lines.push('|---|---|---|---|---|---|---|');

  for (const m of models) {
    lines.push(
      `| ${m.name} | ${m.paramsBillions}B | ${m.vramGb} GB | ${m.toolCalling ? 'PASS' : 'FAIL'} | ${
        m.judgeQuality
      } | ${m.tokPerSecEstimate} | ${m.priority} |`
    );
  }

  lines.push(
    '',
    '## Benchmark History',
    '',
    'See `benchmark-results/` for detailed per-model results.',
    ''
  );

  const readmePath = resolve(pkgDir, 'RECOMMENDATIONS.md');
  writeFileSync(readmePath, lines.join('\n'), 'utf8');
}
